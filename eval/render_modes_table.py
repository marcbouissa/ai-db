"""Generate the mode reference table from the code, so it cannot drift.

Every mode list is read out of `argparse` itself (`ai-db <cmd> --help`) or out of
the module constant that defines it, never out of a literal in this file. A
hand-written table would rot silently the next time a mode is added; the
cross-checks at the bottom raise instead.

Output: docs/MODES.md
"""
from __future__ import annotations

import os
import re
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def help_text(command: str) -> str:
    """`ai-db <command> --help`, straight from argparse."""
    proc = subprocess.run(
        [sys.executable, "-m", "ai_db.cli", command, "--help"],
        capture_output=True, text=True, cwd=REPO, check=False)
    return proc.stdout + proc.stderr


def choices_for(command: str, flag: str) -> list[str]:
    """The value set argparse declares for ``--flag`` on ``command``.

    Tolerates alias lists, which argparse prints as ``--format, --fmt {a,b}``.
    """
    pattern = re.compile(rf"^\s*{re.escape(flag)}\b[^\n{{]*\{{([^}}]*)\}}", re.MULTILINE)
    match = pattern.search(help_text(command))
    if not match:
        raise SystemExit(f"{command}: no choice list found for {flag}")
    return [v.strip() for v in match.group(1).split(",") if v.strip()]


def fmt(values: list[str]) -> str:
    return ", ".join(f"`{v}`" for v in values)


def main() -> int:
    from ai_db.analysis.investigate import MODES as INVESTIGATE_MODES
    from ai_db.analyzer.formatters import ANALYZE_FORMATS, PACK_FORMATS
    from ai_db.config import ALLOWED_DTYPES, EMBEDDING_PROVIDERS, RETRIEVAL_MODES
    from ai_db.parser.ts_graph import SUPPORTED_LANGUAGES
    from ai_db.storage.sqlite_backend import SQLiteBackend

    analyze_depth = choices_for("analyze", "--depth")
    analyze_format = choices_for("analyze", "--format")
    investigate_mode = choices_for("investigate", "--mode")
    investigate_format = choices_for("investigate", "--format")
    expand_depth = choices_for("expand", "--depth")
    expand_format = choices_for("expand", "--format")
    trace_format = choices_for("trace", "--format")
    todo_kind = choices_for("todos", "--kind")
    optimize_fmt = choices_for("optimize", "--default-format")
    route_format = choices_for("route-skill", "--format")
    init_mode = choices_for("init", "--mode")

    # A mode in the code but not the CLI (or the reverse) raises here rather
    # than producing a table that is quietly wrong.
    if set(investigate_mode) != set(INVESTIGATE_MODES):
        raise SystemExit(f"investigate modes differ: {investigate_mode} vs {INVESTIGATE_MODES}")
    if set(analyze_format) != set(ANALYZE_FORMATS):
        raise SystemExit(f"analyze formats differ: {analyze_format} vs {ANALYZE_FORMATS}")
    if set(investigate_format) != set(PACK_FORMATS):
        raise SystemExit(f"pack formats differ: {investigate_format} vs {PACK_FORMATS}")

    doc: list[str] = []
    add = doc.append

    add("# Mode reference")
    add("")
    add("Every mode ai-db exposes, in one place. Generated by "
        "`eval/render_modes_table.py` from `argparse` and from the module constants "
        "that define the modes, so it cannot drift.")
    add("")
    add("Three different things get called a \"mode\", and conflating them is the "
        "usual source of confusion:")
    add("")
    add("| Kind | Set by | Scope |")
    add("|---|---|---|")
    add("| **Query mode** | a flag on one command | that one invocation |")
    add("| **Config mode** | `config.json` or an env var | every invocation until changed |")
    add("| **Depth** | a flag, and often redundant | how much comes back |")
    add("")

    add("## 1. Query modes")
    add("")
    add("### `investigate --mode` — which question is being asked")
    add("")
    add("| Mode | Question it answers | Extra requirement |")
    add("|---|---|---|")
    rows = [
        ("locate", "Where is it? Which files and entry points.", "—"),
        ("explain", "How does it work? Bodies of the seed and its parents.", "—"),
        ("impact", "What breaks if I change it? Callers and callees.", "—"),
        ("flow", "What is the call path? Ordered edges through the graph.", "—"),
        ("diff", "What changed in this commit range?", "`--since` required"),
    ]
    for mode, question, req in rows:
        add(f"| `{mode}` | {question} | {req} |")
    add("")
    add("`diff` is the only mode that needs history; the rest read the index as it "
        "stands. Mode choice changes the pack's *contents*, not its token budget.")
    add("")

    add("### `analyze --format` — how the answer is rendered")
    add("")
    add("| Format | Shape | Counts `tokens_out_formatted` |")
    add("|---|---|---|")
    rows = [
        ("json", "Full dict, machine-readable", "**yes** — the only format that does"),
        ("stub", "Signature per symbol, no bodies", "no"),
        ("sexp", "S-expression, one node per symbol", "no"),
        ("outline", "Nested structural outline", "no"),
        ("prose", "Readable narrative", "no"),
    ]
    for name, shape, counted in rows:
        add(f"| `{name}` | {shape} | {counted} |")
    add("")
    add("The token count is skipped for the four formats a human reads directly: "
        "loading tiktoken's encoder costs ~300 ms once per process against 0.9 ms "
        "per subsequent count, and `json` is the only format whose output is read "
        "by a machine that would look at `meta`.")
    add("")
    add(f"Pack formats (`investigate --format`) are a **different** set: "
        f"{fmt(sorted(PACK_FORMATS))}. At the default 8,000-token budget `stub` is "
        f"8.9x smaller than `json` (3,607 vs 32,438 tokens).")
    add("")

    add("### Depths")
    add("")
    add("| Command | Depths | Default | Note |")
    add("|---|---|---|---|")
    add(f"| `analyze --depth` | {fmt(analyze_depth)} | `structure` | "
        "`summary` and `structure` are **byte-identical** (verified by md5) |")
    add(f"| `expand --depth` | {fmt(expand_depth)} | `full` | `targeted` returns "
        "only the requested span |")
    add("| `trace --depth` | integer, unbounded | `TRACE_DEPTH` | max graph hops |")
    add("")
    add("> Two names, one behaviour: `analyze --depth summary` and "
        "`--depth structure` produce the same bytes. The duplicate is kept for "
        "compatibility, not because the depths differ.")
    add("")

    add("### Other per-invocation flags with a fixed value set")
    add("")
    add("| Flag | Values | Notes |")
    add("|---|---|---|")
    add("| `check` | files on disk (default with a path), `--index` | Two different "
        "questions; both together is an error |")
    add(f"| `trace --format` | {fmt(trace_format)} | |")
    add(f"| `expand --format` | {fmt(expand_format)} | |")
    add(f"| `todos --kind` | {fmt(todo_kind)} | comment markers to look for |")
    add("| `todos --format` | `text`, `json` | |")
    add(f"| `optimize --default-format` | {fmt(optimize_fmt)} | persisted into "
        "session state |")
    add(f"| `route-skill --format` | {fmt(route_format)} | |")
    add(f"| `init --mode` | {fmt(init_mode)} | |")
    add("")

    add("## 2. Config modes (whole installation)")
    add("")
    add("| Setting | Values | Default | Effect |")
    add("|---|---|---|---|")
    add(f"| `retrieval.mode` | {fmt(list(RETRIEVAL_MODES))} | `lexical` | `lexical` "
        "is FTS/BM25 only and needs no model; `hybrid` fuses lexical with dense "
        "vectors weighted by `retrieval.doc_weight` |")
    add(f"| `storage.vector_index` | "
        f"{fmt(list(SQLiteBackend.VECTOR_INDEX_MODES))} | `exact` | `vec0` uses the "
        "sqlite-vec extension, whose KNN is **also brute force** — it is not ANN, "
        "so the 10x target is unreachable on sqlite-vec 0.1.9 |")
    add(f"| `embedding.provider` | {fmt(list(EMBEDDING_PROVIDERS))} | `none` | "
        "`none` means lexical only |")
    add("| `embedding.device` | `auto`, `cpu`, `cuda` | `auto` | measured: CUDA "
        "141.8x faster to index, 10.5x faster to query |")
    add(f"| `embedding.dtype` | {fmt(sorted(ALLOWED_DTYPES))} | `auto` | chosen by a "
        "timing probe, not a guess: float32 0.51 vs bfloat16 0.24 chunks/s measured, "
        "so bfloat16 only wins where the tensor cores exist |")
    add("| `rerank.provider` | `none` or a cross-encoder name | `none` | measured: "
        "`bAAI/bge-reranker-v2-m3` makes retrieval **worse** (MRR 0.785 → 0.555) at "
        "~100x latency — a general MS-Marco model, not code-tuned |")
    add("| `index.ignore` | gitignore-style globs | `[\".agents/**\"]` | extended by "
        "`.aidbignore` at the project root |")
    add("")
    add("Env-var overrides: `AI_DB_RETRIEVAL_MODE`, `AI_DB_PATH`, `AI_DB_CONFIG`, "
        "`AI_DB_SKILL_DIRS`.")
    add("")

    add("## 3. Commonly mistaken for modes")
    add("")
    add("| Thing | What it actually is |")
    add("|---|---|")
    add("| `ref:` handles | Opaque, **process-scoped** pointers minted by "
        "`analyze`/`investigate`. They do not survive a process exit, so `expand` "
        "cannot be scripted across invocations or benchmarked as a subprocess. |")
    add("| `--all-files` | Indexes everything under `--root` instead of only "
        "git-tracked files. Used by the polyglot eval. |")
    add("| `--budget` | A token budget for a pack, not a mode. A lower budget buys "
        "more stubs and omissions, never more tokens. |")
    add("| `meta.tokens_out` | A depth-derived **estimate** of content size, and it "
        "is format-blind: it does not change between `json` and `stub`. Use "
        "`meta.tokens_out_formatted` for real emitted size (CLI only). |")
    add("")

    add("## Coverage and known gaps")
    add("")
    add("| Area | Coverage |")
    add("|---|---|")
    # Language coverage is read from the parser, not written here: a hardcoded
    # count in a doc is exactly the kind of claim that goes stale.
    langs: dict[str, list[str]] = {}
    for ext, lang in SUPPORTED_LANGUAGES.items():
        langs.setdefault(lang, []).append(ext)
    coverage = ", ".join(
        f"{lang} ({', '.join(f'`{e}`' for e in sorted(exts))})"
        for lang, exts in sorted(langs.items()))
    add(f"| Languages parsed | {len(langs)} grammars across "
        f"{len(SUPPORTED_LANGUAGES)} extensions: {coverage} |")
    add("| `check` file validation | tree-sitter for those 9, a per-extension linter "
        "for everything else, both through one `parse_source` path |")
    add("| `tokens_out_formatted` | **CLI only.** Over MCP/HTTP, `analyze` with a "
        "format returns a rendered string (no `meta` to carry the number) and "
        "without a format there is no formatted output to count. Closing that gap "
        "is a transport contract change, not a missing line. |")
    add("")

    dst = os.path.join(REPO, "docs/MODES.md")
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as fh:
        fh.write("\n".join(doc) + "\n")
    print(f"wrote {dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
